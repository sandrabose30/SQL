-- Topics: Aggregate functions, GROUP BY, HAVING, JOIN, subqueries
-- 11.	Calculate the total sales Amount across all transactions.
select sum(amount) as total_sales
from sales;
-- 12.	Find the total sales Amount generated by each product.
select sum(s.amount) as total_sales, pr.product
from sales s
left join products pr
on s.pid=pr.pid
group by pr.product;
-- 13.	Calculate the total Boxes Shipped by each salesperson.
select sum(s.boxes) as total_boxes, Salesperson
from sales s
left join people p
on s.spid=p.spid
group by p.salesperson;
-- 14.	Count the number of sales transactions for each country.
select count(s.amount) as No_of_sales, g.geo as country
from sales s
left join geo g
on s.GeoID=g.GeoID
group by country;
-- 15.	Find the average transaction Amount for each product.
select avg(s.amount) as total_sales, pr.product
from sales s
left join products pr
on s.pid=pr.pid
group by pr.product;
-- 16.	Display products whose total sales Amount exceeds 10,000.
select sum(s.amount) as total_sales, pr.product
from sales s
left join products pr
on s.pid=pr.pid
group by pr.product
having total_sales > 10000;
-- 17.	Find the top 5 salespeople based on their total sales Amount.
select sum(s.amount) as total_sales, Salesperson
from sales s
left join people p
on s.spid=p.spid
group by p.salesperson
order by total_sales desc
limit 5;
-- 18.	Join the sales and products tables to display each product's name, category, and sales Amount.
select s.amount, pr.product, pr.Category
from sales s
left join products pr
on s.pid=pr.pid;
-- 19.	Calculate total sales Amount for each country and sort the results from highest to lowest.
select sum(s.amount) as total_sales, g.geo as country
from sales s
left join geo g
on s.GeoID=g.GeoID
group by country
order by total_sales desc;
-- 20.	Find salespeople whose total sales Amount is greater than the average Amount of all individual transactions.
select sum(s.amount) as total_sales, avg(s.amount) as avg_sales, Salesperson
from sales s
left join people p
on s.spid=p.spid
group by p.salesperson
having total_sales > avg_sales;

-- Topics: Window functions, ROW_NUMBER(), PARTITION BY, LAG(), LEAD(), subqueries, ranking
-- 21.	ROW_NUMBER(): Assign a unique row number to every sales transaction, ordered by Amount from highest to lowest.
SELECT amount, row_number() over(order by amount) as row_num 
from sales;
-- 22.	ROW_NUMBER() + PARTITION BY: Assign row numbers to each salesperson's transactions, ordering by Amount from highest to lowest. 
-- Restart numbering for every salesperson.
select s.amount, p.salesperson, ROW_NUMBER() OVER (PARTITION BY s.SPID ORDER BY s.Amount DESC) AS Row_Num
from sales s
left join people p
on s.spid=p.spid;
-- 23.	LAG(): For each salesperson, display the current transaction's Amount and the previous transaction's Amount, ordered by SaleDate.
SELECT s.SPID, p.Salesperson, s.SaleDate, s.Amount, LAG(s.Amount) OVER (PARTITION BY s.SPID ORDER BY s.SaleDate) AS Previous_Amount
FROM sales s
JOIN people p ON s.SPID = p.SPID;
-- 24.	LEAD(): For each salesperson, display the current transaction's Amount and the next transaction's Amount, ordered by SaleDate.
SELECT s.SPID, p.Salesperson, s.SaleDate, s.Amount, lead(s.Amount) OVER (PARTITION BY s.SPID ORDER BY s.SaleDate) AS next_Amount
FROM sales s
JOIN people p ON s.SPID = p.SPID;
-- 25.	LAG() + PARTITION BY: Calculate the difference between each transaction's Amount and the salesperson's previous transaction Amount.
SELECT s.SPID, p.Salesperson, s.SaleDate, s.Amount, LAG(s.Amount) OVER (PARTITION BY s.SPID ORDER BY s.SaleDate) AS Previous_Amount, (s.amount - LAG(s.Amount) OVER (PARTITION BY s.SPID ORDER BY s.SaleDate)) as Amount_Difference
FROM sales s
JOIN people p ON s.SPID = p.SPID;
-- 26.	LEAD() + PARTITION BY: Display each salesperson's current SaleDate and Amount, along with their next transaction's SaleDate and Amount.
SELECT s.SPID, p.Salesperson, s.SaleDate, s.Amount, LEAD(s.SaleDate) OVER (PARTITION BY s.SPID ORDER BY s.SaleDate) AS Next_SaleDate, lead(s.Amount) OVER (PARTITION BY s.SPID ORDER BY s.SaleDate) AS Next_Amount
FROM sales s
JOIN people p ON s.SPID = p.SPID;
