-- 5.	List all unique product names from the products table.
select distinct product
from products;
-- 6.	Find all sales records for the product named 'After Nines'.
select s.amount, pr.product
from sales s
left join products pr
on s.pid = pr.pid
where pr.product = 'After Nines';
-- 7.	Display sales transactions where the Amount is between 500 and 2,000.
select * 
from sales
